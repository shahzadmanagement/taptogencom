/**
 * SYSTEM 1: UNIQUE FAQ ENGINE
 * Generates 6 to 8 completely unique FAQs per tool based on specific tool characteristics,
 * keyword parameters, category focus, privacy, and technical execution.
 */
export function getUniqueFaqsForTool(tool: Tool, lang: string = 'en'): FAQItem[] {
  const name = tool.name;
  const kw = tool.primaryKeyword || tool.name;
  const cat = tool.categorySlug || 'utility';
  const desc = tool.description.replace(/<[^>]*>/g, '');

  const baseFaqs: FAQItem[] = [];

  // Q1: What makes this tool specific
  baseFaqs.push({
    q: `How does the ${name} process data for ${kw}?`,
    a: `The ${name} uses client-side JavaScript algorithms to transform your input into ${kw} results instantly in your browser without communicating with external API servers.`
  });

  // Q2: Key customization & input controls
  baseFaqs.push({
    q: `What options can I adjust when generating ${kw}?`,
    a: `You can customize parameters such as tone, output quantity, structural formatting, and style presets from the control panel to tailor output specifically for ${name} requirements.`
  });

  // Q3: Data privacy & security execution
  baseFaqs.push({
    q: `Is my input data saved or uploaded when using ${name}?`,
    a: `No. All text processing for ${name} is executed 100% locally inside your web browser session. No prompt inputs, generated names, or text content are logged, transmitted, or stored on server databases.`
  });

  // Q4: Commercial usage rights
  baseFaqs.push({
    q: `Can I use generated ${kw} outputs for commercial projects?`,
    a: `Yes. You hold full ownership of all text outputs produced by ${name}. You may use them freely in commercial software, branding, social media, publishing, or client deliverables.`
  });

  // Q5: Category-specific depth FAQ
  if (cat.includes('name') || cat.includes('fantasy')) {
    baseFaqs.push({
      q: `What should I verify before registering a generated ${name} concept?`,
      a: `We recommend conducting a quick local trademark search and checking domain or social handle availability before committing to a commercial brand or character name.`
    });
    baseFaqs.push({
      q: `How does ${name} handle cultural and phonetic variation?`,
      a: `Our naming engine combines historical word roots, phonetic syllable patterns, and stylistic prefixes to ensure natural linguistic cadence across different naming styles.`
    });
  } else if (cat.includes('text') || cat.includes('font')) {
    baseFaqs.push({
      q: `Will styled ${name} text display properly on mobile devices?`,
      a: `Yes. The generated output uses standard Unicode mathematical and alphanumeric characters supported by modern iOS, Android, macOS, Windows, and Linux operating systems.`
    });
    baseFaqs.push({
      q: `Why do some screen readers read Unicode styled text differently?`,
      a: `Unicode font generators use mathematical symbols that look like letters. Screen readers may read these symbols as mathematical terms rather than plain words, so we recommend reserving fancy text for decorative headlines.`
    });
  } else if (cat.includes('seo') || cat.includes('developer')) {
    baseFaqs.push({
      q: `Is the output code from ${name} compliant with current web standards?`,
      a: `Yes. Code snippets and tags generated by ${name} follow standard W3C, RFC, and schema.org specifications for seamless integration into modern web frameworks.`
    });
    baseFaqs.push({
      q: `How do I validate the generated code before deploying to production?`,
      a: `You can copy the generated code directly into official linters, Google Search Console URL inspection tools, or browser dev tools to verify syntax before publishing.`
    });
  } else {
    baseFaqs.push({
      q: `What is the maximum character or item limit for ${name}?`,
      a: `The generator is optimized for instant browser rendering and can process large text blocks up to tens of thousands of characters without performance degradation.`
    });
    baseFaqs.push({
      q: `Does ${name} require installing software or browser extensions?`,
      a: `No installation is required. ${name} runs directly in any modern web browser on desktop, tablet, or smartphone.`
    });
  }

  // Q7: Export & Clipboard integration
  baseFaqs.push({
    q: `How do I export or copy results from ${name}?`,
    a: `You can click the one-tap 'Copy' button beside individual outputs or use 'Copy All' to save the complete generated set directly to your system clipboard.`
  });

  return baseFaqs;
}

